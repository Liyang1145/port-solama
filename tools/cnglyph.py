#!/usr/bin/env python3
# b_neon_sign (Hark modelling lane, 2026-11-22): offline CJK glyph atlas for map B (霓港) signs, so the shop signs / light boxes /
# holo billboards no longer depend on the player's system Chinese font (no font -> tofu boxes before).
# Scans the string literals of the B sign modules for CJK characters, renders ONLY those glyphs from Noto Sans SC Bold
# (SIL Open Font License 1.1, (c) 2014-2021 Adobe) into a white-on-transparent atlas, and writes the character order to
# src/maps/cyber/cnglyph_chars.js. The font file itself is NOT shipped (only the rendered bitmap subset).
# usage: python3 tools/cnglyph.py /path/to/NotoSansSC-Bold.otf
import re, sys, math
from PIL import Image, ImageDraw, ImageFont

SRC = ['src/maps/cyber/street2.js', 'src/maps/cyber/neon.js', 'src/maps/cyber/neontube.js']
CELL, PX, COLS = 128, 112, 16
font_path = sys.argv[1] if len(sys.argv) > 1 else '/workspace/work/gal/aud2/NotoSC.otf'

chars = set()
for f in SRC:
    try: t = open(f, encoding='utf8').read()
    except FileNotFoundError: continue
    t = re.sub(r'//[^\n]*', '', t)
    for m in re.finditer(r"'([^'\n]*)'|\"([^\"\n]*)\"|`([^`]*)`", t):
        s = next(g for g in m.groups() if g is not None)
        chars |= {c for c in s if '\u3400' <= c <= '\u9fff' or '\u3000' <= c <= '\u303f' or '\uff00' <= c <= '\uffef'}
chars = ''.join(sorted(chars))
rows = math.ceil(len(chars) / COLS)
img = Image.new('LA', (COLS * CELL, rows * CELL), (255, 0))
alpha = Image.new('L', img.size, 0); d = ImageDraw.Draw(alpha)
font = ImageFont.truetype(font_path, PX)
for i, c in enumerate(chars):
    x0, y0 = (i % COLS) * CELL, (i // COLS) * CELL
    d.text((x0 + CELL / 2, y0 + CELL / 2), c, font=font, fill=255, anchor='mm')
img.putalpha(alpha)
img.save('dist/assets/cnglyph.png', optimize=True)
open('src/maps/cyber/cnglyph_chars.js', 'w', encoding='utf8').write(
    '// generated by tools/cnglyph.py — glyph order of dist/assets/cnglyph.png (Noto Sans SC Bold subset, SIL OFL 1.1)\n'
    f'export const CN_CELL = {CELL}, CN_COLS = {COLS};\nexport const CN_CHARS = {chars!r};\n'.replace("'", "'"))
print(len(chars), 'glyphs', img.size)
